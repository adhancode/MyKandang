-- Menampilkan daftar tabel pada skema public untuk memeriksa tabel yang tersedia.
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;

-- Menampilkan semua kolom akun untuk pemeriksaan; hasilnya juga mencakup hash kata sandi.
SELECT * FROM pengguna;

-- Menampilkan katalog hewan beserta nama kategori, harga, stok, dan statusnya.
SELECT
    h.id_hewan,
    h.nama,
    k.nama_kategori,
    h.harga,
    h.stok,
    h.status
FROM hewan h
JOIN kategori_hewan k
    ON h.id_kategori = k.id_kategori;

-- Menampilkan ringkasan pesanan bersama identitas pengguna yang membuat pesanan.
SELECT
    p.id_pesanan,
    pg.id_pengguna,
    pg.nama AS nama_pengguna,
    p.tgl_pesanan,
    p.total_harga,
    p.metode_serah_terima,
    p.status_pesanan
FROM pesanan p
JOIN pengguna pg
    ON p.id_pengguna = pg.id_pengguna;

-- Menampilkan item tiap pesanan beserta harga, kuantitas, dan subtotalnya.
SELECT
    dp.id_pesanan,
    h.nama AS nama_hewan,
    dp.harga_satuan,
    dp.kuantitas,
    dp.subtotal
FROM detail_pesanan dp
JOIN hewan h
    ON dp.id_hewan = h.id_hewan
ORDER BY dp.id_pesanan;

