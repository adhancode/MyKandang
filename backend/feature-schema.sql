CREATE TABLE IF NOT EXISTS alamat_pengguna (
  id_alamat INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INT NOT NULL REFERENCES pengguna(id_pengguna) ON DELETE CASCADE,
  label VARCHAR(60) NOT NULL DEFAULT 'Alamat rumah',
  nama_penerima VARCHAR(100) NOT NULL,
  no_telepon VARCHAR(20),
  alamat TEXT NOT NULL,
  utama BOOLEAN NOT NULL DEFAULT FALSE,
  dibuat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS alamat_pengguna_satu_utama
  ON alamat_pengguna(id_pengguna) WHERE utama=TRUE;

INSERT INTO alamat_pengguna(id_pengguna,label,nama_penerima,no_telepon,alamat,utama)
SELECT p.id_pengguna,'Alamat utama',p.nama,p.no_telepon,p.alamat,TRUE
FROM pengguna p
WHERE NULLIF(BTRIM(p.alamat),'') IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM alamat_pengguna a WHERE a.id_pengguna=p.id_pengguna);

CREATE TABLE IF NOT EXISTS penjual (
  id_penjual INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INT NOT NULL UNIQUE REFERENCES pengguna(id_pengguna) ON DELETE CASCADE,
  nama_toko VARCHAR(120) NOT NULL,
  deskripsi TEXT,
  no_telepon VARCHAR(20),
  alamat VARCHAR(255),
  foto_url VARCHAR(255),
  status VARCHAR(20) NOT NULL DEFAULT 'Menunggu',
  dibuat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (status IN ('Menunggu','Aktif','Ditolak','Nonaktif'))
);

ALTER TABLE hewan
  ADD COLUMN IF NOT EXISTS id_penjual INT REFERENCES penjual(id_penjual) ON DELETE SET NULL;

ALTER TABLE pesanan
  ADD COLUMN IF NOT EXISTS jadwal_serah_terima TIMESTAMPTZ;

ALTER TABLE chat
  ADD COLUMN IF NOT EXISTS id_penjual INT REFERENCES penjual(id_penjual) ON DELETE CASCADE;

CREATE UNIQUE INDEX IF NOT EXISTS chat_pengguna_penjual_unik
  ON chat(id_pengguna,id_penjual) WHERE id_penjual IS NOT NULL;

CREATE TABLE IF NOT EXISTS notifikasi (
  id_notifikasi INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna INT NOT NULL REFERENCES pengguna(id_pengguna) ON DELETE CASCADE,
  judul VARCHAR(120) NOT NULL,
  pesan VARCHAR(500) NOT NULL,
  jenis VARCHAR(40) NOT NULL DEFAULT 'info',
  data JSONB NOT NULL DEFAULT '{}'::jsonb,
  dibaca BOOLEAN NOT NULL DEFAULT FALSE,
  dibuat TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS notifikasi_pengguna_terbaru
  ON notifikasi(id_pengguna,dibaca,dibuat DESC);
