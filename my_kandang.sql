BEGIN;

CREATE TABLE pengguna (
    id_pengguna INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    no_telepon VARCHAR(20),
    alamat VARCHAR(255),
    role VARCHAR(20) NOT NULL DEFAULT 'customer',
    CHECK (role IN ('customer', 'staff_admin'))
);

CREATE TABLE kategori_hewan (
    id_kategori INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kategori VARCHAR(100) NOT NULL,
    deskripsi TEXT
);

CREATE TABLE hewan (
    id_hewan INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_kategori INT NOT NULL,
    nama VARCHAR(100) NOT NULL,
    jenis VARCHAR(100),
    ras VARCHAR(100),
    jenis_kelamin VARCHAR(10),
    berat NUMERIC(10,2),
    umur INT,
    kondisi_kesehatan VARCHAR(255),
    harga NUMERIC(15,2) NOT NULL,
    stok INT NOT NULL DEFAULT 0,
    deskripsi TEXT,
    status VARCHAR(50) NOT NULL DEFAULT 'Tersedia',
    FOREIGN KEY (id_kategori)
        REFERENCES kategori_hewan(id_kategori)
        ON UPDATE CASCADE,
    CHECK (jenis_kelamin IS NULL OR jenis_kelamin IN ('Jantan', 'Betina')),
    CHECK (berat IS NULL OR berat >= 0),
    CHECK (umur IS NULL OR umur >= 0),
    CHECK (harga >= 0),
    CHECK (stok >= 0)
);

CREATE TABLE gambar_hewan (
    id_gambar INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_hewan INT NOT NULL,
    url VARCHAR(255) NOT NULL,
    gambar_utama BOOLEAN DEFAULT FALSE,
    FOREIGN KEY (id_hewan)
        REFERENCES hewan(id_hewan)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE pesanan (
    id_pesanan INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna INT NOT NULL,
    tgl_pesanan TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_harga NUMERIC(15,2) NOT NULL DEFAULT 0,
    metode_serah_terima VARCHAR(50) NOT NULL,
    alamat_pengiriman VARCHAR(255),
    status_pesanan VARCHAR(50) DEFAULT 'Pending',
    FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
        ON UPDATE CASCADE,
    CHECK (total_harga >= 0)
);

CREATE TABLE detail_pesanan (
    id_detail INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pesanan INT NOT NULL,
    id_hewan INT NOT NULL,
    harga_satuan NUMERIC(15,2) NOT NULL,
    kuantitas INT NOT NULL,
    subtotal NUMERIC(15,2)
        GENERATED ALWAYS AS (harga_satuan * kuantitas) STORED,
    FOREIGN KEY (id_pesanan)
        REFERENCES pesanan(id_pesanan)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (id_hewan)
        REFERENCES hewan(id_hewan)
        ON UPDATE CASCADE,
    UNIQUE (id_pesanan, id_hewan),
    CHECK (harga_satuan >= 0),
    CHECK (kuantitas > 0)
);

CREATE TABLE pembayaran (
    id_pembayaran INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pesanan INT NOT NULL UNIQUE,
    metode VARCHAR(100),
    jumlah NUMERIC(15,2) NOT NULL,
    tanggal_bayar TIMESTAMP,
    status VARCHAR(50) DEFAULT 'Belum Dibayar',
    bukti VARCHAR(255),
    FOREIGN KEY (id_pesanan)
        REFERENCES pesanan(id_pesanan)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CHECK (jumlah >= 0)
);

CREATE TABLE keranjang (
    id_keranjang INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna INT NOT NULL,
    tanggal_dibuat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(50),
    FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE detail_keranjang (
    id_detail_keranjang INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_keranjang INT NOT NULL,
    id_hewan INT NOT NULL,
    jumlah INT NOT NULL DEFAULT 1,
    FOREIGN KEY (id_keranjang)
        REFERENCES keranjang(id_keranjang)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (id_hewan)
        REFERENCES hewan(id_hewan)
        ON UPDATE CASCADE,
    UNIQUE (id_keranjang, id_hewan),
    CHECK (jumlah > 0)
);

CREATE TABLE wishlist (
    id_wishlist INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna INT NOT NULL,
    id_hewan INT NOT NULL,
    tanggal_ditambahkan TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (id_hewan)
        REFERENCES hewan(id_hewan)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    UNIQUE (id_pengguna, id_hewan)
);

CREATE TABLE ulasan (
    id_ulasan INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna INT NOT NULL,
    id_hewan INT NOT NULL,
    id_pesanan INT NOT NULL,
    rating INT NOT NULL,
    komentar VARCHAR(500),
    tanggal DATE DEFAULT CURRENT_DATE,
    FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
        ON UPDATE CASCADE,
    FOREIGN KEY (id_hewan)
        REFERENCES hewan(id_hewan)
        ON UPDATE CASCADE,
    FOREIGN KEY (id_pesanan)
        REFERENCES pesanan(id_pesanan)
        ON UPDATE CASCADE,
    CHECK (rating BETWEEN 1 AND 5)
);

CREATE TABLE chat (
    id_chat INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pengguna INT NOT NULL,
    tanggal_dibuat TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(50),
    FOREIGN KEY (id_pengguna)
        REFERENCES pengguna(id_pengguna)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE pesan_chat (
    id_pesan INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chat INT NOT NULL,
    id_pengirim INT NOT NULL,
    isi_pesan TEXT NOT NULL,
    waktu_kirim TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status_baca VARCHAR(50) DEFAULT 'Belum Dibaca',
    FOREIGN KEY (id_chat)
        REFERENCES chat(id_chat)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    FOREIGN KEY (id_pengirim)
        REFERENCES pengguna(id_pengguna)
        ON UPDATE CASCADE
);

